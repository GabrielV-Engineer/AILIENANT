# Phase 4.1.4 — Legacy → new role-name migration (blueprint §3.1).
# Maps the deprecated 5-value vocabulary onto the canonical 8-value vocabulary.
# Consumed by WBSStep.__migrate_legacy_target_role__ as a before-validator so
# every stored target_role is always one of the 8 NEW canonical names. The legacy
# 5 values + this map will be removed one release after Phase 4 closes (logged
# in PROJECT_MANIFEST.md Tech Debt section).
_LEGACY_TO_NEW_ROLE: Dict[str, str] = {
    "Refactor": "architect_refactor",
    "Infra": "devops_infra",
    "Doc": "doc_manager",
    "SecOps": "secops",
    "Test": "qa_tester",
}

# Phase 7.12 — canonical post-migration role vocabulary. An out-of-vocabulary
# target_role string hallucinated by the Planner is coerced to this default rather
# than raising a ValidationError (which would burn a planner retry).
_CANONICAL_ROLES: frozenset[str] = frozenset({
    "core_dev", "architect_refactor", "devops_infra", "secops",
    "qa_tester", "doc_manager", "vcs_manager", "data_ml_engineer",
})
_DEFAULT_ROLE = "core_dev"


def _coerce_to_str(item: Any) -> str:
    """Phase 7.12 — flatten a hallucinated list element into a plain string.

    The Planner LLM intermittently emits objects (``{"file": "x", "reason": "y"}``)
    where the MissionSpecification contract requires a ``str``. Rather than fail
    validation, flatten: dicts become ``"key: value"`` pairs; everything else is
    stringified. Already-strings pass through untouched.
    """
    if isinstance(item, str):
        return item
    if isinstance(item, dict):
        return "; ".join(f"{k}: {v}" for k, v in item.items())
    return str(item)


def _coerce_str_list(value: Any) -> Any:
    """Phase 7.12 — normalise a value destined for a ``List[str]`` field.

    Maps each element through :func:`_coerce_to_str`. A bare scalar/dict (LLM
    emitted a single value instead of a list) is wrapped into a one-element list.
    Non-coercible input is returned unchanged so Pydantic still fails loudly.
    """
    if isinstance(value, list):
        return [_coerce_to_str(el) for el in value]
    if isinstance(value, (str, dict)):
        return [_coerce_to_str(value)]
    return value


class WBSStep(BaseModel):
    """A single, atomic, executable step within a MissionSpecification.

    The target_role Literal accepts both legacy (5) and new (8) canonical values.
    A model_validator(mode="before") normalises legacy strings to canonical names
    at construction, so the stored value is always one of the 8 canonical names.
    """

    step_number: int = Field(
        description="Sequential execution order (1, 2, 3...)."
    )
    target_role: Literal[
        # Legacy 5 (deprecated, auto-migrated to the new vocabulary):
        "Refactor", "Infra", "Doc", "SecOps", "Test",
        # New 8 (canonical Phase 4 vocabulary):
        "core_dev", "architect_refactor", "devops_infra", "secops",
        "qa_tester", "doc_manager", "vcs_manager", "data_ml_engineer",
    ] = Field(
        default="core_dev",
        description="The RBAC role the CoderAgent assumes for this step (Phase 4.1.4).",
    )
    action: Literal["read_file", "write_file", "edit_file", "run_command"] = Field(
        description="Strict action type for this step."
    )
    target_file: str = Field(
        description="Exact path of the affected file (e.g. 'src/routes/auth.py') or command to run."
    )
    description: str = Field(
        description="Detailed instruction for the CoderAgent to execute at this step."
    )
    status: Literal[
        "pending", "in_progress", "completed", "failed",
        # 13.0.9 — incremental per-step approval widens the lifecycle: a step
        # generated by the coder now pauses for a human decision before it is
        # honestly "completed". awaiting_approval = generated, pending a
        # human decision; rejected = terminal, the human declined it outright
        # (distinct from failed, which is a system-side fault); revision_requested =
        # non-terminal, the human asked for a different attempt with feedback,
        # re-dispatched to the coder (bounded by APPLY_REJECT_MAX_ATTEMPTS).
        "awaiting_approval", "rejected", "revision_requested",
    ] = Field(
        default="pending",
        description="Current task state. The Orchestrator mutates this field during execution.",
    )
    requires_iteration: bool = Field(
        default=False,
        description=(
            "Routes this step to the autonomous ReAct execution cell (continuous "
            "run-read-edit-rerun loop over a live terminal) instead of the one-shot "
            "coder path. Set for multi-step debugging / test-fix / iterate-until-green "
            "work; leave False for trivial single-shot edits and commands. Additive and "
            "backward-compatible: older plans without the field default to the one-shot path."
        ),
    )
    depends_on: Optional[List[int]] = Field(
        default=None,
        description=(
            "Optional list of step_numbers this step depends on. When present, "
            "ValidateWBSDependenciesTool enforces that the resulting graph is acyclic "
            "and that every referenced step_number exists in the same plan. Additive "
            "and backward-compatible: older plans without this field deserialize as None."
        ),
    )
    agent_notes: Optional[str] = Field(
        default=None,
        description=(
            "A directive FOR THE CODER ONLY (e.g. a tool-usage constraint a post-"
            "generation annotator appends, such as the polyglot-file patch-tool "
            "requirement) — never rendered on the human-facing checklist, never "
            "folded into a semantic-cache key or a retrieval query. Additive and "
            "backward-compatible: older plans without this field deserialize as None."
        ),
    )

    @model_validator(mode="before")
    @classmethod
    def _migrate_legacy_target_role(cls, data: Any) -> Any:
        """Map legacy 5-value role names to new 8-value canonical names.

        Runs BEFORE Pydantic field validation so the Literal narrows cleanly to
        the post-migration set. Idempotent: already-new values pass through
        unchanged. Tolerates non-dict input (Pydantic internal construction).
        """
        if isinstance(data, dict):
            legacy = data.get("target_role")
            if isinstance(legacy, str) and legacy in _LEGACY_TO_NEW_ROLE:
                data["target_role"] = _LEGACY_TO_NEW_ROLE[legacy]
            # Coerce an out-of-vocabulary role to the safe default instead of
            # raising a Literal ValidationError.
            role = data.get("target_role")
            if isinstance(role, str) and role not in _CANONICAL_ROLES:
                data["target_role"] = _DEFAULT_ROLE
        return data


# 13.0.9 — three call sites (engine.py's RELAY selector, guardrails.py's stall
# guard, guardrails.py's advance predicate) all select WBS steps by status, and
# guardrails.py's route_after_validation documents their agreement as an
# invariant: "Uses the SAME status == 'pending' predicate route_to_coders
# selects on, so routing and dispatch never disagree." Widening the status
# vocabulary (revision_requested, awaiting_approval, rejected) breaks that
# invariant in three DIFFERENT ways unless all three move together — a
# revision never re-dispatched, a turn ending early instead of revising, or a
# non-advancing step never tripping the stall guard. One shared predicate pair
# instead of three copies of a status tuple is what keeps them from drifting
# apart again later.
_DISPATCHABLE_STATUSES: frozenset[str] = frozenset({"pending", "revision_requested"})
_TERMINAL_STATUSES: frozenset[str] = frozenset({"completed", "failed", "rejected"})


def is_dispatchable(step: "WBSStep", all_steps: Optional[List["WBSStep"]] = None) -> bool:
    """True when a step is eligible to be sent to a coder — it has never run
    (``pending``) or a human asked for a different attempt
    (``revision_requested``) — AND, when ``all_steps`` is supplied, every
    step named in its ``depends_on`` has itself reached ``completed``.

    ``all_steps`` is optional so this stays a drop-in for any single-argument
    caller; the two live dispatch-selection sites (``route_to_coders`` and
    ``route_after_validation``'s stall guard, per the shared-predicate
    invariant above) pass the full task list precisely so a step whose
    declared prerequisite was rejected or failed can no longer dispatch and
    run against whatever that prerequisite left on disk — or didn't.
    """
    if step.status not in _DISPATCHABLE_STATUSES:
        return False
    # getattr, not direct attribute access: several call sites (both real and
    # test-only) pass lightweight stand-ins for WBSStep that never carry this
    # field.
    depends_on = getattr(step, "depends_on", None)
    if depends_on and all_steps is not None:
        completed = {s.step_number for s in all_steps if s.status == "completed"}
        if not all(dep in completed for dep in depends_on):
            return False
    return True


def is_terminal(step: "WBSStep") -> bool:
    """True when a step has reached an end state the RELAY loop will never
    revisit: applied (``completed``), a system-side fault (``failed``), or a
    human declined it outright (``rejected``). ``awaiting_approval`` and
    ``revision_requested`` are deliberately NOT terminal — the former is mid-
    decision, the latter is dispatchable again."""
    return step.status in _TERMINAL_STATUSES


class MissionSpecification(BaseModel):
    """
    THE MACRO-CONTRACT (Spec-Driven Development).
    Forces the PlannerAgent to define the complete architecture before writing a single line of code.
    """

    outcome: str = Field(
        description="The final expected result and the value this mission delivers."
    )
    scope: List[str] = Field(
        description="Strict definition of what is IN and OUT of scope. Which files to touch and which NOT to."
    )
    constraints: List[str] = Field(
        description="Technical limitations (e.g. no external libraries, O(n) complexity, project conventions)."
    )
    decisions: List[str] = Field(
        description="Design or architecture decisions adopted to solve this particular problem. "
        "Convention: when a technology stack was chosen or confirmed for this mission, it is "
        "recorded as the first entry (see agents/planner.py::_STACK_GUIDANCE_DIRECTIVE) — "
        "to_context_block() below relies on that ordering to survive truncation."
    )
    tasks: List[WBSStep] = Field(
        description="Work Breakdown Structure (WBS). The strict, sequential list of steps to execute."
    )
    checks: List[str] = Field(
        description="Technical acceptance criteria. How will the Testing micro-swarm know the task succeeded?"
    )
    # Optional; defaults preserve backward compatibility with plans authored before
    # these DDD/SDD/TDD fields existed.
    ubiquitous_language: Dict[str, str] = Field(
        default_factory=dict,
        description="DDD: domain terms → definitions extracted from the Socratic session.",
    )
    deep_modules_sdd: Optional[str] = Field(
        default=None,
        description="Architectural SDD for core modules identified during ideation.",
    )
    tdd_criteria: List[str] = Field(
        default_factory=list,
        description="TDD acceptance criteria generated from the Socratic Q&A session.",
    )

    @model_validator(mode="before")
    @classmethod
    def _coerce_hallucinated_str_lists(cls, data: Any) -> Any:
        """Coerce dict/scalar hallucinations in the ``List[str]`` fields.

        The contract (immutable per SCHEMA_EVOLUTION.MD) is unchanged: these fields
        remain ``List[str]``. This before-validator only normalises malformed LLM
        output (objects where strings belong) so a structurally-valid plan no longer
        burns a retry. Mirrors WBSStep._migrate_legacy_target_role. Idempotent and
        tolerant of non-dict input (Pydantic internal construction).
        """
        if isinstance(data, dict):
            for _field in ("scope", "constraints", "decisions", "checks", "tdd_criteria"):
                if _field in data and data[_field] is not None:
                    data[_field] = _coerce_str_list(data[_field])
        return data

    def to_context_block(self, max_entries: int = 6, max_chars: int = 600) -> str:
        """Bounded projection of this mission's ``decisions``/``constraints`` for a code
        generator's prompt (both `agents/coder.py` and `brain/agentic_cell.py` consume this).

        Neither generator reads `mission_spec` for anything beyond step lookup/status today,
        so a stack choice recorded in `decisions` (see that field's docstring — the stack
        entry is convention-first) never reached the code it was meant to constrain, and a
        multi-step build could drift per step. This method is the single, bounded seam that
        fixes that without widening the wire contract: it emits data, not a new field.

        `decisions` are emitted before `constraints`, and both are truncated (never silently
        dropped) once `max_chars` is exhausted — the stack decision, always the first `decisions`
        entry by convention, is therefore the last thing to be cut under pressure. Returns ""
        when there is nothing to say, so a caller can splice it in unconditionally.
        """
        lines: List[str] = []
        for label, items in (("Decision", self.decisions), ("Constraint", self.constraints)):
            for item in items[:max_entries]:
                lines.append(f"- {label}: {item}")

        if not lines:
            return ""

        body = "\n".join(lines)
        if len(body) > max_chars:
            body = body[:max_chars].rstrip() + " …"
        return "MISSION CONTEXT (binding — decisions already made for this build):\n" + body


