def _merge_generated_code(
    left: Dict[str, "VFSFile"], right: Dict[str, "VFSFile"]
) -> Dict[str, "VFSFile"]:
    """Reducer for parallel CoderAgent output buffers. Keeps the entry with the
    lexicographically later document_version_id so the most recent generated edit
    survives multi-agent fan-out collisions."""
    merged = dict(left)
    for path, file in right.items():
        if path not in merged or file.document_version_id > merged[path].document_version_id:
            merged[path] = file
    return merged


def _merge_vfs(left: Dict[str, "VFSFile"], right: Dict[str, "VFSFile"]) -> Dict[str, "VFSFile"]:
    """Reducer for concurrent CoderAgent VFS writes. Keeps the file with the
    lexicographically later document_version_id (timestamp/hash), preventing
    a slower parallel branch from overwriting a more recent edit."""
    merged = dict(left)
    for path, file in right.items():
        if path not in merged or file.document_version_id > merged[path].document_version_id:
            merged[path] = file
    return merged


def _merge_messages(
    existing: List[Dict[str, str]],
    update: List[Dict[str, str]],
) -> List[Dict[str, str]]:
    """Default: append (operator.add semantics).
    If update[0] has __replace__=True, replace entire history with the rest of update.
    """
    if update and update[0].get("__replace__"):
        return [m for m in update if not m.get("__replace__")]
    return existing + update


def _resolve_step_id(left: Optional[int], right: Optional[int]) -> Optional[int]:
    """Reducer for current_step_id under SWARM fan-out. The MapReduce router sends one
    CoderAgent per WBS task in the same super-step, and each writes its own step_number
    back; with no reducer LangGraph cannot merge the concurrent scalar writes and raises
    INVALID_CONCURRENT_GRAPH_UPDATE. Keep the highest step_number so the post-swarm
    pointer advances monotonically toward completion. None is the 'no pending step'
    sentinel (e.g. the orchestrator's all-complete write) and is treated as 'no opinion',
    so it never clobbers a concurrent real step."""
    if left is None:
        return right
    if right is None:
        return left
    return max(left, right)


def _resolve_target_role(left: Optional[str], right: Optional[str]) -> Optional[str]:
    """Reducer for target_role under SWARM fan-out. The MapReduce router sends one
    CoderAgent per WBS task in the same super-step, and each writes back the role of
    the step it handled; with no reducer LangGraph cannot merge the concurrent scalar
    writes and raises INVALID_CONCURRENT_GRAPH_UPDATE. Keep the latest non-None write
    — None is the 'no opinion' sentinel (e.g. the orchestrator's all-complete reset)
    and never clobbers a concurrent real role."""
    return right if right is not None else left


def _merge_todos(
    left: Optional[List[Dict[str, Any]]], right: Optional[List[Dict[str, Any]]]
) -> List[Dict[str, Any]]:
    """Reducer for an agent's TODO list — replace-semantics, swarm-safe.

    A write rewrites the whole list (the tool always emits the full set), so the latest
    write wins. The distinction that matters: None means 'no opinion this turn' and keeps
    the prior list, while an explicit empty list [] means 'I finished — clear my panel'.
    Testing truthiness (``right if right else left``) would make that clear impossible —
    an empty list would be read as 'no opinion' and the completed TODOs would never go
    away. So branch on ``is not None``, never on emptiness."""
    if right is not None:
        return right
    return left or []


class AIlienantGraphState(TypedDict):
    """
    The shared brain of the LangGraph flow.
    Strictly defines the memory and variables nodes may read or mutate.
    """

    # --- Mission Identity ---
    task_id: str
    user_input: str
    # Wall-clock epoch (time.time()) set once by core/task_service.py's
    # session-start resolver on the first turn of a session, then carried
    # forward unchanged on every later turn while L1 stays warm. No graph
    # node ever writes this — read-only downstream, used to derive session
    # duration for context-utilization telemetry. Absent/None on a checkpoint
    # written before this field existed.
    session_start_time: Optional[float]

    # --- Workspace Identity & Manual Context (Phase 1.1.0 / 1.1.0.4) ---
    project_id: Optional[str]              # SHA-256 of the VS Code workspace root path
    workspace_root: Optional[str]          # Absolute path of the VS Code workspace; set from _workspace_registry
    explicit_mentions: List[str]           # @-referenced file paths → forced full-file read
    attachments: List[ManualAttachment]    # user-attached images / documents

    # --- Message Memory ---
    # O(N) cumulative history backing the conversational channel.
    messages: Annotated[List[Dict[str, str]], _merge_messages]

    # --- Context & Telemetry ---
    context_metrics: ContextMeter
    active_llm_profile: LLMProfile
    token_usage: TokenCounter

    # --- Flow Control (Prompt Swapping) ---
    is_manual_override: bool
    # Reducer-guarded: SWARM fan-out makes multiple CoderAgents write their own
    # step's role in one super-step; _resolve_target_role merges them (see docstring).
    target_role: Annotated[
        Optional[str], _resolve_target_role
    ]  # Replaces 'target_agent'. The active CoderAgent role.
    # Reducer-guarded: SWARM fan-out makes multiple CoderAgents write their own
    # step_number in one super-step; _resolve_step_id merges them (see its docstring).
    current_step_id: Annotated[
        Optional[int], _resolve_step_id
    ]  # Pointer to the WBS task currently executing (step_number).

    # --- Human-in-the-Loop & Planner Mode (Phase 1.4 / 2.21) ---
    planner_mode_active: bool       # True when user toggled Planner-only mode via WS event
    hitl_pending: bool              # True while the graph is awaiting human approval
    hitl_response: Optional[str]   # "approved" | "rejected" + optional comment from HITL response
    shared_understanding_reached: bool  # Phase 2.21: True once analyst confirms Socratic dialogue complete
    # ideation_synthesized: set by synthesis_node once the Socratic dialogue is distilled
    #   into a planner brief; route_after_ideation reads it to hand the turn to
    #   planner_agent instead of dead-ending at END. Scalar overwrite (written once per
    #   synthesis turn). MUST stay declared here — LangGraph silently drops any state key
    #   a node returns that isn't a channel on this TypedDict (see assert_declared_channels
    #   below), which is exactly how this handoff went dark before it was declared.
    ideation_synthesized: bool
    # ideation_glossary: ubiquitous language ({term: definition}) settled during the
    #   Socratic dialogue, folded into the planner's context. Scalar overwrite.
    ideation_glossary: Dict[str, str]
    # grill_round_count: how many analyst_grill rounds have run this ideation session.
    #   Each round is now its own graph super-step (a self-loop edge on analyst_grill,
    #   brain/ideation.py), with the human's answer for that round resolved via native
    #   interrupt()/resume rather than a fresh top-level invocation — so a round cannot
    #   track its own count in a local Python variable the way the old
    #   one-question-per-top-level-turn design implicitly did via separate invocations.
    #   Scalar overwrite; used as the _GRILL_MAX_ROUNDS circuit breaker.
    grill_round_count: int
    # pending_grill_batch: the current round's question batch (already-serialized
    #   dicts, questions_to_pending_dicts' output), committed to state by
    #   analyst_grill's generate phase BEFORE the self-loop revisits the node for
    #   its ask phase. Required by the same invariant pending_exec_command/
    #   pending_tool_call/pending_hitl_request enforce elsewhere (brain/agentic_cell.py):
    #   interrupt() must be the node's FIRST action, since LangGraph replays
    #   everything before it on every resume — a batch generated in the SAME
    #   invocation that calls interrupt() would be silently regenerated
    #   (non-deterministically) on replay, misaligning the ids the operator
    #   actually answered. None once the ask phase resolves and clears it.
    pending_grill_batch: Optional[List[Dict[str, Any]]]
    # pending_brief: the distilled planner brief awaiting the operator's review,
    #   committed by synthesis_node's draft phase before the self-loop revisits the
    #   node for its review phase — the same defer-then-interrupt-first invariant
    #   pending_grill_batch enforces above, and for a costlier reason: the draft is
    #   a MODEL_BIG call, so a brief generated in the same invocation that calls
    #   interrupt() would be regenerated on every replay, silently charging for a
    #   brief the operator never saw and swapping out the text under review.
    #   Carries the composed brief ("composed" — rendered verbatim for review, since
    #   _compose_planner_brief already emits the settled constraints and scope as
    #   their own labelled blocks, which is what makes an OMITTED one noticeable)
    #   plus the glossary, which becomes ideation_glossary only once accepted.
    #   None once the review resolves. Scalar overwrite.
    pending_brief: Optional[Dict[str, Any]]
    # brief_revision_note: the operator's steering instruction when they send a brief
    #   back to be rewritten. Consumed by the next draft phase (appended to the
    #   distillation's user payload, never to its system prompt) and cleared there.
    #   Scalar overwrite.
    brief_revision_note: Optional[str]
    # Agentic-cell exec-approval deferral: the command awaiting human approval, set when
    # the cell defers a HITL-gated run_terminal so the interrupt happens in a clean,
    # side-effect-free re-entry rather than mid-iteration.
    pending_exec_command: Optional[str]
    # Agentic-cell registry-fallback deferral (DEBT-129): a HITL-tier tool name outside
    # the 3 CELL_TOOLS primitives, awaiting human approval before it executes. Mirrors
    # pending_exec_command's defer-then-interrupt-first pattern for an arbitrary
    # registry-resolved tool call rather than the single hardcoded run_terminal command.
